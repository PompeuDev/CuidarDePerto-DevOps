-- CRIACAO DAS TABELAS

-- 1. TABELA IDOSO

CREATE TABLE T_CDP_IDOSO (
    ID_IDOSO NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    NM_IDOSO NVARCHAR2(100) NOT NULL,
    NR_IDADE NUMBER(10) NOT NULL,
    DS_ENDERECO NVARCHAR2(200),

    CONSTRAINT PK_T_CDP_IDOSO
        PRIMARY KEY (ID_IDOSO)
);


-- 2. TABELA ALERTA

CREATE TABLE T_CDP_ALERTA (
    ID_ALERTA NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    DS_TIPO_ALERTA NVARCHAR2(100) NOT NULL,
    DT_ALERTA TIMESTAMP(7) NOT NULL,
    ID_IDOSO NUMBER(10) NOT NULL,

    CONSTRAINT PK_T_CDP_ALERTA
        PRIMARY KEY (ID_ALERTA),

    CONSTRAINT FK_CDP_ALERTA_IDOSO
        FOREIGN KEY (ID_IDOSO)
        REFERENCES T_CDP_IDOSO (ID_IDOSO)
        ON DELETE CASCADE
);

CREATE INDEX IX_T_CDP_ALERTA_ID_IDOSO
    ON T_CDP_ALERTA (ID_IDOSO);


-- 3. TABELA CUIDADOR

CREATE TABLE T_CDP_CUIDADOR (
    ID_CUIDADOR NUMBER(10) NOT NULL,
    NM_CUIDADOR VARCHAR2(100) NOT NULL,
    DS_CONTATO VARCHAR2(80),
    ID_IDOSO NUMBER(10) NOT NULL,

    CONSTRAINT PK_CDP_CUIDADOR
        PRIMARY KEY (ID_CUIDADOR),

    CONSTRAINT FK_CDP_CUIDADOR_IDOSO
        FOREIGN KEY (ID_IDOSO)
        REFERENCES T_CDP_IDOSO (ID_IDOSO)
        ON DELETE CASCADE
);


-- 4. TABELA ATENDIMENTO

CREATE TABLE T_CDP_ATENDIMENTO (
    ID_ATENDIMENTO NUMBER(10) NOT NULL,
    ID_ALERTA NUMBER(10) NOT NULL,
    ID_CUIDADOR NUMBER(10) NOT NULL,
    DT_ATENDIMENTO TIMESTAMP(7) NOT NULL,
    DS_STATUS VARCHAR2(20) NOT NULL,
    DS_OBSERVACAO VARCHAR2(200),

    CONSTRAINT PK_CDP_ATENDIMENTO
        PRIMARY KEY (ID_ATENDIMENTO),

    CONSTRAINT FK_CDP_ATEND_ALERTA
        FOREIGN KEY (ID_ALERTA)
        REFERENCES T_CDP_ALERTA (ID_ALERTA)
        ON DELETE CASCADE,

    CONSTRAINT FK_CDP_ATEND_CUIDADOR
        FOREIGN KEY (ID_CUIDADOR)
        REFERENCES T_CDP_CUIDADOR (ID_CUIDADOR)
        ON DELETE CASCADE,

    CONSTRAINT CK_CDP_ATEND_STATUS
        CHECK (DS_STATUS IN (
            'ABERTO',
            'EM_ANDAMENTO',
            'CONCLUIDO'
        ))
        
);

