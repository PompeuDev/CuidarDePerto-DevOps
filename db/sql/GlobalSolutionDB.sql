    DBMS_OUTPUT.PUT_LINE('Total de alertas: ' || v_total_alertas);

END;
/




-- CLASSIFICACAO DE PRIORIDADE DOS ALERTAS

DECLARE
    v_total_alertas NUMBER;
    v_id_idoso NUMBER := 1;

BEGIN
    SELECT COUNT(*) INTO v_total_alertas
    FROM T_CDP_ALERTA
    WHERE ID_IDOSO = v_id_idoso;

    IF v_total_alertas >= 3 THEN
        DBMS_OUTPUT.PUT_LINE('Prioridade alta');

    ELSIF v_total_alertas >= 1 THEN
        DBMS_OUTPUT.PUT_LINE('Prioridade media');

    ELSE
        DBMS_OUTPUT.PUT_LINE('Prioridade baixa');

    END IF;

    DBMS_OUTPUT.PUT_LINE('Total de alertas: ' || v_total_alertas);

END;
/



-- CONSULTA DE ALERTAS POR IDOSO

DECLARE
    v_id_idoso NUMBER;
    v_nome_idoso NVARCHAR2(100);
    v_total_alertas NUMBER;
    v_total_geral NUMBER := 0;

BEGIN
    SELECT MIN(ID_IDOSO) INTO v_id_idoso
    FROM T_CDP_IDOSO;

    WHILE v_id_idoso IS NOT NULL LOOP

        SELECT NM_IDOSO INTO v_nome_idoso
        FROM T_CDP_IDOSO
        WHERE ID_IDOSO = v_id_idoso;

        SELECT COUNT(*) INTO v_total_alertas
        FROM T_CDP_ALERTA
        WHERE ID_IDOSO = v_id_idoso;

        DBMS_OUTPUT.PUT_LINE(
            v_nome_idoso || ' - Alertas: ' || v_total_alertas
        );

        v_total_geral := v_total_geral + v_total_alertas;

        SELECT MIN(ID_IDOSO) INTO v_id_idoso
        FROM T_CDP_IDOSO
        WHERE ID_IDOSO > v_id_idoso;

    END LOOP;

    DBMS_OUTPUT.PUT_LINE('Total geral de alertas: ' || v_total_geral);

END;
/




-- CONSULTA DOS ALERTAS COM CURSOR

DECLARE
    CURSOR c_alertas IS
        SELECT ID_ALERTA, DS_TIPO_ALERTA, ID_IDOSO
        FROM T_CDP_ALERTA
        ORDER BY ID_ALERTA;

    v_alerta c_alertas%ROWTYPE;

BEGIN
    OPEN c_alertas;

    LOOP
        FETCH c_alertas INTO v_alerta;
        EXIT WHEN c_alertas%NOTFOUND;

        DBMS_OUTPUT.PUT_LINE(
            'Alerta: ' || v_alerta.ID_ALERTA ||
            ' - Tipo: ' || v_alerta.DS_TIPO_ALERTA ||
            ' - Idoso: ' || v_alerta.ID_IDOSO
        );

    END LOOP;

    CLOSE c_alertas;

END;
/



-- ATUALIZACAO DO STATUS DO ATENDIMENTO

CREATE OR REPLACE PROCEDURE ATUALIZAR_STATUS_ATENDIMENTO (
    p_id_atendimento IN NUMBER,
    p_novo_status IN VARCHAR2
)
AS
BEGIN
    IF p_novo_status IN ('ABERTO', 'EM_ANDAMENTO', 'CONCLUIDO') THEN

        UPDATE T_CDP_ATENDIMENTO
        SET DS_STATUS = p_novo_status
        WHERE ID_ATENDIMENTO = p_id_atendimento;

        IF SQL%ROWCOUNT > 0 THEN
            DBMS_OUTPUT.PUT_LINE('Status atualizado com sucesso!');
        ELSE
            DBMS_OUTPUT.PUT_LINE('Atendimento nao encontrado!');
        END IF;

    ELSE
        DBMS_OUTPUT.PUT_LINE('Status invalido!');
    END IF;
END;
/



