-- CONSULTA DE ALERTAS DO IDOSO

CREATE OR REPLACE PROCEDURE CONSULTAR_ALERTAS_IDOSO (
    p_id_idoso IN NUMBER
)
AS
    v_nome_idoso NVARCHAR2(100);
    v_total_alertas NUMBER;

BEGIN
    SELECT NM_IDOSO INTO v_nome_idoso
    FROM T_CDP_IDOSO
    WHERE ID_IDOSO = p_id_idoso;

    SELECT COUNT(*) INTO v_total_alertas
    FROM T_CDP_ALERTA
    WHERE ID_IDOSO = p_id_idoso;

    DBMS_OUTPUT.PUT_LINE('Idoso: ' || v_nome_idoso);
    DBMS_OUTPUT.PUT_LINE('Total de alertas: ' || v_total_alertas);

EXCEPTION
    WHEN NO_DATA_FOUND THEN
        DBMS_OUTPUT.PUT_LINE('Idoso nao encontrado!');
END;
/




